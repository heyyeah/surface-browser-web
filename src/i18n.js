// Order of authority: an explicit ?lang= (so a link can pin a language), then a
// remembered choice, then the browser. `preferred` is navigator.languages;
// region tags match on their base (de-CH finds German). Unmatched is English.
export function resolveLanguage({ override = "", stored = "", preferred = [] } = {}) {
  const fromOverride = normalizeLanguage(override);
  if (fromOverride) {
    return fromOverride;
  }
  const fromStored = normalizeLanguage(stored);
  if (fromStored) {
    return fromStored;
  }
  for (const candidate of Array.isArray(preferred) ? preferred : []) {
    const match = normalizeLanguage(candidate);
    if (match) {
      return match;
    }
  }
  return DEFAULT_LANGUAGE;
}

export function normalizeLanguage(value) {
  // Split on either separator: navigator.languages uses hyphens ("de-CH") but a
  // hand-typed ?lang= may use the POSIX form ("de_DE").
  const base = String(value || "").trim().toLowerCase().split(/[-_]/)[0];
  return SUPPORTED_LANGUAGES.includes(base) ? base : "";
}

// A missing key falls back to English and then to the key itself, so a
// developer sees something; scripts/i18n.test.mjs checks completeness.
export function translate(key, lang = DEFAULT_LANGUAGE, params = null) {
  const table = STRINGS[lang] || STRINGS[DEFAULT_LANGUAGE];
  const text = table[key] ?? STRINGS[DEFAULT_LANGUAGE][key] ?? key;
  if (!params) {
    return text;
  }
  // A function replacer, so a `$` in a value (a query, a message) is literal.
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function languageTable(lang) {
  return STRINGS[lang] || STRINGS[DEFAULT_LANGUAGE];
}

export function allLanguageTables() {
  return STRINGS;
}

// --- runtime (the only part that touches the DOM) --------------------------

const STORAGE_KEY = "surfaceBrowser.language";
let activeLanguage = DEFAULT_LANGUAGE;

export function getLanguage() {
  return activeLanguage;
}

// Wrapper so callers read `t("nav.back")` without threading the language.
export function t(key, params = null) {
  return translate(key, activeLanguage, params);
}

export function initLanguage() {
  activeLanguage = resolveLanguage({
    override: readUrlLanguage(),
    stored: readStoredLanguage(),
    preferred: readBrowserLanguages()
  });
  applyLanguageToDocument();
  return activeLanguage;
}

export function setLanguage(lang) {
  const next = normalizeLanguage(lang);
  if (!next || next === activeLanguage) {
    return activeLanguage;
  }
  activeLanguage = next;
  try {
    window.localStorage?.setItem(STORAGE_KEY, next);
  } catch {
    // A private window throws; not remembering the choice is no reason to refuse it
    // for this session.
  }
  applyLanguageToDocument();
  return activeLanguage;
}

function readUrlLanguage() {
  try {
    return new URLSearchParams(window.location.search).get("lang") || "";
  } catch {
    return "";
  }
}

function readStoredLanguage() {
  try {
    return window.localStorage?.getItem(STORAGE_KEY) || "";
  } catch {
    return "";
  }
}

function readBrowserLanguages() {
  try {
    return navigator.languages?.length ? [...navigator.languages] : [navigator.language || ""];
  } catch {
    return [];
  }
}

function applyLanguageToDocument() {
  // Sets `<html lang>`, which screen readers pick a voice from and browsers offer
  // to translate against.
  try {
    document.documentElement.lang = activeLanguage;
  } catch {
    // No document (a test importing this module). Nothing to label.
  }
  applyStaticTranslations();
}

// Walks the markup rather than a list of element ids, so a translatable control
// needs only an attribute in index.html.
//
//   data-i18n="nav.back"                 -> textContent
//   data-i18n-attr="title:nav.back,..."  -> named attributes
export function applyStaticTranslations(root = document) {
  if (!root?.querySelectorAll) {
    return;
  }
  for (const node of root.querySelectorAll("[data-i18n]")) {
    node.textContent = t(node.dataset.i18n);
  }
  for (const node of root.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of node.dataset.i18nAttr.split(",")) {
      const [attr, key] = pair.split(":").map((part) => part.trim());
      if (attr && key) {
        node.setAttribute(attr, t(key));
      }
    }
  }
}
